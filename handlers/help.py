def help_keyboard() -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup([
        [InlineKeyboardButton("وظيفة البوت الاساسية", callback_data="help_basic")],
        [InlineKeyboardButton("طريقة السلة الذكية AI", callback_data="help_smart_cart")],
    ])


async def help_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "اختر الموضوع الذي تريد معرفة تفاصيله:",
        reply_markup=help_keyboard(),
    )


async def help_topic_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    topic_text = {
        "help_basic": BASIC_USAGE_TEXT,
        "help_smart_cart": SMART_CART_HELP_TEXT,
    }.get(query.data)

    if topic_text is not None:
        await query.message.reply_text(topic_text)
